export function appText(locale, key, vars = {}) {
  const lang = locale === 'en' ? 'en' : 'ru';
  const lookup = (source) => String(key || '').split('.').reduce((current, part) => current?.[part], source);
  let value = lookup(copy[lang]);
  if (value == null) value = lookup(copy.ru);
  if (value == null) return key;
  return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => vars[name] ?? `{${name}}`);
}
