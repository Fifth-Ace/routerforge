// Package ipintel provides a bounded, side-effect-free selection layer for
// RouterForge DNS A/AAAA answers. The caller owns DNS RRset boundaries, cache,
// DNSSEC and client identity. This package never starts network probes.
package ipintel

import (
	"hash/fnv"
	"math/rand"
	"net/netip"
	"sort"
	"strings"
	"sync"
	"time"
)

// Mode selects the ordering policy. Empty is Original for upgrade safety.
type Mode string

const (
	Original    Mode = "original"
	RoundRobin  Mode = "round_robin"
	Random      Mode = "random"
	Fastest     Mode = "fastest"
	HealthAware Mode = "health_aware"
	Adaptive    Mode = "adaptive"
	Sticky      Mode = "sticky"
	Weighted    Mode = "weighted"
	HealthyOnly Mode = "healthy_only"
)

func (m Mode) Valid() bool {
	switch m {
	case "", Original, RoundRobin, Random, Fastest, HealthAware, Adaptive, Sticky, Weighted, HealthyOnly:
		return true
	}
	return false
}

// Health is sampled independently of the incoming DNS request.
// An unknown sample is NEVER interpreted as down.
type Health struct {
	Checked bool
	Healthy bool
	RTT     time.Duration
	Weight  int // 1..100 for Weighted; 0 means use default weight 1.
}

type Planner struct {
	mu      sync.Mutex
	cursors map[string]uint64
	rng     *rand.Rand
}

func New(seed int64) *Planner {
	return &Planner{cursors: make(map[string]uint64), rng: rand.New(rand.NewSource(seed))}
}
func (p *Planner) next(key string) uint64 {
	p.mu.Lock()
	defer p.mu.Unlock()
	if len(p.cursors) > 4096 {
		p.cursors = make(map[string]uint64)
	}
	n := p.cursors[key]
	p.cursors[key] = n + 1
	return n
}
func (p *Planner) shuffle(values []netip.Addr) {
	p.mu.Lock()
	defer p.mu.Unlock()
	p.rng.Shuffle(len(values), func(i, j int) { values[i], values[j] = values[j], values[i] })
}
func rotate(a []netip.Addr, idx int) {
	if len(a) < 2 {
		return
	}
	idx %= len(a)
	a2 := append(append([]netip.Addr(nil), a[idx:]...), a[:idx]...)
	copy(a, a2)
}
func hash(s string) uint64                                 { h := fnv.New64a(); _, _ = h.Write([]byte(s)); return h.Sum64() }
func sample(h map[netip.Addr]Health, ip netip.Addr) Health { return h[ip] }
func rank(h Health) int {
	if !h.Checked {
		return 1
	}
	if h.Healthy {
		return 0
	}
	return 2
}
func score(h Health) time.Duration {
	if !h.Checked || !h.Healthy || h.RTT <= 0 {
		return time.Duration(1 << 62)
	}
	return h.RTT
}
func weight(h Health) int {
	if h.Weight < 1 {
		return 1
	}
	if h.Weight > 100 {
		return 100
	}
	return h.Weight
}

// Order returns a fresh slice. It does not modify the input or any health map.
// key must be a qname + qtype + policy-identity key generated by the caller.
// client must be a VERIFIED device identity for Sticky; empty disables stickiness.
// The caller must supply only one A or one AAAA RRset at a time (never mix).
func (p *Planner) Order(mode Mode, key, client string, original []netip.Addr, metrics map[netip.Addr]Health) []netip.Addr {
	out := append([]netip.Addr(nil), original...)
	if len(out) < 2 || mode == "" || mode == Original || !mode.Valid() {
		return out
	}
	switch mode {
	case RoundRobin:
		rotate(out, int(p.next(key)%uint64(len(out))))
	case Random:
		p.shuffle(out)
	case Fastest:
		sort.SliceStable(out, func(i, j int) bool { return score(sample(metrics, out[i])) < score(sample(metrics, out[j])) })
	case HealthAware:
		sort.SliceStable(out, func(i, j int) bool { return rank(sample(metrics, out[i])) < rank(sample(metrics, out[j])) })
	case Adaptive:
		sort.SliceStable(out, func(i, j int) bool {
			a, b := sample(metrics, out[i]), sample(metrics, out[j])
			if rank(a) != rank(b) {
				return rank(a) < rank(b)
			}
			return score(a) < score(b)
		})
		// Rotate only inside the healthiest available tier, respecting its RTT bands.
		if len(out) > 1 {
			firstRank := rank(sample(metrics, out[0]))
			n := 0
			for n < len(out) && rank(sample(metrics, out[n])) == firstRank {
				n++
			}
			if n > 1 {
				rotate(out[:n], int(p.next(key)%uint64(n)))
			}
		}
	case Sticky:
		if strings.TrimSpace(client) == "" {
			rotate(out, int(p.next(key)%uint64(len(out))))
			break
		}
		// HRW hashing: preference is stable even across process-local counters.
		sort.SliceStable(out, func(i, j int) bool {
			ai := hash(key + "|" + client + "|" + out[i].String())
			aj := hash(key + "|" + client + "|" + out[j].String())
			return ai > aj
		})
	case Weighted:
		// Deterministic smooth weighted selection of the first IP by request counter.
		// We still return the complete set (instead of duplicating records).
		total := uint64(0)
		for _, ip := range out {
			total += uint64(weight(sample(metrics, ip)))
		}
		draw := p.next(key) % total
		index := 0
		for i, ip := range out {
			w := uint64(weight(sample(metrics, ip)))
			if draw < w {
				index = i
				break
			}
			draw -= w
		}
		rotate(out, index)
	case HealthyOnly:
		healthy := make([]netip.Addr, 0, len(out))
		for _, ip := range out {
			h := sample(metrics, ip)
			if !h.Checked || h.Healthy {
				healthy = append(healthy, ip)
			}
		}
		if len(healthy) > 0 {
			out = healthy
		} // all unknown/down = preserve original, never return empty.
	}
	return out
}
